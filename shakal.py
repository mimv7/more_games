import random

# Список игроков и доступных цветов
players = ["Игрок 1", "Игрок 2", "Игрок 3"]
colors = ["Белый", "Черный", "Красный", "Желтый"]

# Перемешиваем список цветов случайным образом
random.shuffle(colors)

# Объединяем игроков с перемешанными цветами и выводим результат
print("🎨 Результаты распределения цветов:")
for player, color in zip(players, colors):
    print(f"🔹 {player} получает цвет: {color}")
